import { describe, expect, it } from 'vitest';

import {
  ADMIN_CREATURES,
  ADMIN_ITEMS,
  buildItemsetCommand,
  buildSpawnCommand,
  normalizeItemAmount,
  normalizeItemsetLevel,
  searchAdminCreatures,
  searchAdminItems,
} from '@/lib/admin-items';

describe('admin item catalog', () => {
  it('contains the full research catalog', () => {
    expect(ADMIN_ITEMS.length).toBeGreaterThanOrEqual(120);
    expect(ADMIN_CREATURES.length).toBeGreaterThanOrEqual(25);
  });

  it('has unique prefabs and non-empty names', () => {
    const itemPrefabs = ADMIN_ITEMS.map((item) => item.prefab);
    const creaturePrefabs = ADMIN_CREATURES.map((creature) => creature.prefab);

    expect(new Set(itemPrefabs).size).toBe(itemPrefabs.length);
    expect(new Set(creaturePrefabs).size).toBe(creaturePrefabs.length);

    for (const entry of [...ADMIN_ITEMS, ...ADMIN_CREATURES]) {
      expect(entry.prefab.length).toBeGreaterThan(0);
      expect(entry.name.length).toBeGreaterThan(0);
      expect(entry.nameEn.length).toBeGreaterThan(0);
    }
  });

  it('searches by prefab, Russian and English names', () => {
    expect(searchAdminItems('SwordIron').map((item) => item.prefab)).toEqual(['SwordIron']);
    expect(searchAdminItems('железный меч').some((item) => item.prefab === 'SwordIron')).toBe(true);
    expect(searchAdminItems('iron sword').map((item) => item.prefab)).toContain('SwordIron');
    expect(searchAdminItems('   ')).toHaveLength(ADMIN_ITEMS.length);
    expect(searchAdminItems('нет-такого-предмета')).toHaveLength(0);

    expect(searchAdminCreatures('Troll').map((creature) => creature.prefab)).toEqual(
      expect.arrayContaining(['Troll']),
    );
    expect(searchAdminCreatures('тролль').some((creature) => creature.prefab === 'Troll')).toBe(
      true,
    );
  });

  it('filters by category', () => {
    const weapons = searchAdminItems('', 'weapons');
    const food = searchAdminItems('', 'food');
    const bosses = searchAdminCreatures('', 'bosses');

    expect(weapons.length).toBeGreaterThan(10);
    expect(weapons.every((item) => item.category === 'weapons')).toBe(true);
    expect(food.every((item) => item.category === 'food')).toBe(true);
    expect(bosses.length).toBeGreaterThan(2);
    expect(bosses.every((creature) => creature.category === 'bosses')).toBe(true);
  });

  it('marks equipment categories as quality-capable (metadata from research)', () => {
    expect(searchAdminItems('SwordIron')[0]?.hasQuality).toBe(true);
    expect(searchAdminItems('Wood').find((item) => item.prefab === 'Wood')?.hasQuality).toBe(false);
  });
});

describe('console command builders', () => {
  it('builds spawn commands for items and creatures', () => {
    expect(buildSpawnCommand('SwordIron', 1)).toBe('spawn SwordIron 1');
    expect(buildSpawnCommand('Wood', 50)).toBe('spawn Wood 50');
    expect(buildSpawnCommand('Boar')).toBe('spawn Boar 1');
    expect(buildSpawnCommand('Troll', 3)).toBe('spawn Troll 3');
    expect(buildSpawnCommand('Wolf', 0)).toBe('spawn Wolf 1');
  });

  it('clamps amount and itemset level to safe limits', () => {
    expect(normalizeItemAmount(0)).toBe(1);
    expect(normalizeItemAmount(1_000_000)).toBe(9999);
    expect(normalizeItemAmount(Number.NaN)).toBe(1);
    expect(normalizeItemsetLevel(0)).toBe(1);
    expect(normalizeItemsetLevel(9)).toBe(5);
    expect(normalizeItemsetLevel(Number.NaN)).toBe(1);
  });

  it('builds itemset commands with level and keep flag', () => {
    expect(buildItemsetCommand('Ashlands', 4)).toBe('itemset Ashlands 4');
    expect(buildItemsetCommand('Meadows')).toBe('itemset Meadows 1');
    expect(buildItemsetCommand('AshlandsMage', 5, true)).toBe('itemset AshlandsMage 5 1');
    expect(buildItemsetCommand('  Ashlands  ', 9)).toBe('itemset Ashlands 5');
  });
});

