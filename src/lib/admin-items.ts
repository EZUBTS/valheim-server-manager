/**
 * Каталог предметов и существ для выдачи через F5-консоль.
 *
 * Данные: `docs/admin-items.json` (Valheim 1.0.21); prefab-имена сверены
 * с дампом Jotunn и реестром консоли игры. `prefab` не переводится —
 * именно он вводится в консоли.
 */

export type AdminItemCategory =
  'weapons' | 'armor' | 'arrows' | 'tools' | 'materials' | 'ores' | 'food' | 'meads' | 'trophies';

export type AdminCreatureCategory = 'animals' | 'monsters' | 'bosses';

export interface AdminItem {
  /** Внутреннее имя предмета (prefab) — вводится в консоли как есть. */
  prefab: string;
  /** Русское название для каталога. */
  name: string;
  /** Английское название (для поиска). */
  nameEn: string;
  category: AdminItemCategory;
  /** Экипировка, для которой имеет смысл качество 1–5. */
  hasQuality: boolean;
  /** Подсказка из research-документа (источник, применение). */
  note: string | null;
}

export interface AdminCreature {
  /** Внутреннее имя существа (prefab) для команды `spawn`. */
  prefab: string;
  name: string;
  nameEn: string;
  category: AdminCreatureCategory;
  note: string | null;
}

