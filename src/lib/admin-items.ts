/** Ограничивает количество предметов допустимым диапазоном. */
export function normalizeItemAmount(value: number): number {
  if (!Number.isFinite(value)) {
    return ITEM_AMOUNT_MIN;
  }

  return Math.min(ITEM_AMOUNT_MAX, Math.max(ITEM_AMOUNT_MIN, Math.trunc(value)));
}

/** Ограничивает уровень предметов в наборе диапазоном 1–5. */
export function normalizeItemsetLevel(value: number): number {
  if (!Number.isFinite(value)) {
    return ITEMSET_LEVEL_MIN;
  }

  return Math.min(ITEMSET_LEVEL_MAX, Math.max(ITEMSET_LEVEL_MIN, Math.trunc(value)));
}

/**
 * Собирает консольную команду спавна предмета/существа:
 * `spawn <prefab> <amount>` (для существ доступны level/radius, см. каталог команд).
 */
export function buildSpawnCommand(prefab: string, amount = 1): string {
  return 'spawn ' + prefab.trim() + ' ' + normalizeItemAmount(amount);
}

/**
 * Собирает команду готового набора экипировки:
 * `itemset <name> <level> [keep]` — `keep` оставляет уже надетые предметы.
 */
export function buildItemsetCommand(preset: string, level = 1, keep = false): string {
  const parts = ['itemset', preset.trim(), String(normalizeItemsetLevel(level))];

  if (keep) {
    parts.push('1');
  }

  return parts.join(' ').trim();
}

function itemMatches(item: AdminItem, query: string): boolean {
  const needle = query.trim().toLowerCase();

  if (!needle) {
    return true;
  }

  return (
    item.prefab.toLowerCase().includes(needle) ||
    item.name.toLowerCase().includes(needle) ||
    item.nameEn.toLowerCase().includes(needle) ||
    (item.note !== null && item.note.toLowerCase().includes(needle))
  );
}

function creatureMatches(creature: AdminCreature, query: string): boolean {
  const needle = query.trim().toLowerCase();

  if (!needle) {
    return true;
  }

  return (
    creature.prefab.toLowerCase().includes(needle) ||
    creature.name.toLowerCase().includes(needle) ||
    creature.nameEn.toLowerCase().includes(needle) ||
    (creature.note !== null && creature.note.toLowerCase().includes(needle))
  );
}

/** Поиск предметов по prefab, русскому/английскому названию и подсказке. */
export function searchAdminItems(
  query: string,
  category: AdminItemCategory | 'all' = 'all',
): AdminItem[] {
  return ADMIN_ITEMS.filter(
    (item) => (category === 'all' || item.category === category) && itemMatches(item, query),
  );
}

/** Поиск существ по prefab, названию и подсказке. */
export function searchAdminCreatures(
  query: string,
  category: AdminCreatureCategory | 'all' = 'all',
): AdminCreature[] {
  return ADMIN_CREATURES.filter(
    (creature) =>
      (category === 'all' || creature.category === category) && creatureMatches(creature, query),
  );
}
