export function getAdminCommandBadges(command: AdminCommand): string[] {
  const badges: string[] = [];

  if (command.source === 'mod') {
    badges.push('только с модом');
  }

  if (command.requiresDevcommands) {
    badges.push('требует devcommands');
  }

  if (command.onlyInGame) {
    badges.push('только в игре');
  } else if (
    command.category === 'Модерация' ||
    ['save', 'ping', 'info', 'banned'].includes(command.id)
  ) {
    badges.push('на выделенном сервере');
  }

  if (command.id === 'devcommands') {
    badges.push('на сервере нужен мод');
  }

  return badges;
}
