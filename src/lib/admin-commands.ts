export interface AdminCommandGroup {
  category: AdminCommandCategory;
  label: string;
  commands: AdminCommand[];
}

function commandMatches(command: AdminCommand, query: string): boolean {
  const needle = query.trim().toLowerCase();

  if (!needle) {
    return true;
  }

  return (
    command.id.toLowerCase().includes(needle) ||
    command.name.toLowerCase().includes(needle) ||
    command.syntax.toLowerCase().includes(needle) ||
    command.description.toLowerCase().includes(needle) ||
    command.category.toLowerCase().includes(needle) ||
    (command.note !== null && command.note.toLowerCase().includes(needle))
  );
}

/** Поиск по названию/синтаксису/описанию/примечанию; без запроса возвращает всё. */
export function searchAdminCommands(query: string): AdminCommand[] {
  return ADMIN_COMMANDS.filter((command) => commandMatches(command, query));
}

/** Группирует команды по категориям в порядке реестра игры. */
export function groupAdminCommands(
  commands: readonly AdminCommand[] = ADMIN_COMMANDS,
): AdminCommandGroup[] {
  return ADMIN_COMMAND_CATEGORY_ORDER.map((category) => ({
    category,
    label: category,
    commands: commands.filter((command) => command.category === category),
  })).filter((group) => group.commands.length > 0);
}

